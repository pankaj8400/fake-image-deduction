"""Pydantic schemas for API request and response data models."""

from typing import List, Dict, Optional, Any
from pydantic import BaseModel, Field


class ClassConfidence(BaseModel):
    """Confidence metrics for an individual detection class."""
    class_name: str = Field(..., description="Target class: real, ai_generated, faceswap, or photoshop")
    confidence: float = Field(..., description="Normalized confidence probability [0.0 - 1.0]")
    percentage: float = Field(..., description="Confidence represented as percentage [0.0 - 100.0]")


class ForensicMetrics(BaseModel):
    """Forensic signals extracted from the dual-branch neural network."""
    srm_residual_energy: float = Field(..., description="Mean energy of SRM high-pass filtered noise residual")
    dominant_kernel: str = Field(..., description="Dominant filter kernel identifying tampering (Laplacian, Edge, or Star)")
    spatial_feature_norm: float = Field(..., description="L2 norm of the spatial ConvNeXt feature map")
    attention_spatial_ratio: float = Field(..., description="Ratio of attention assigned to spatial branch [0.0 - 1.0]")
    attention_frequency_ratio: float = Field(..., description="Ratio of attention assigned to frequency branch [0.0 - 1.0]")
    margin: Optional[float] = Field(default=None, description="Difference between top class and runner-up confidence")
    runner_up_class: Optional[str] = Field(default=None, description="Second most probable class")
    runner_up_confidence: Optional[float] = Field(default=None, description="Confidence of second most probable class")
    noise_inconsistency: Optional[float] = Field(default=None, description="Spatial noise variance between face center and background")
    vit_32_patch_anomaly: Optional[float] = Field(default=None, description="ViT-B/32 patch token anomaly standard deviation across 32x32 image patches")
    vit_synthesis_score: Optional[float] = Field(default=None, description="Prebuilt ViT-B/32 AI synthesis indicator [0.0 - 1.0]")
    fft_high_frequency_ratio: Optional[float] = Field(default=None, description="2D FFT high-frequency spectral ratio")
    gradient_micro_energy: Optional[float] = Field(default=None, description="Average micro-texture gradient norm")
    vit_scene_category: Optional[str] = Field(default=None, description="ViT-B/32 top predicted ImageNet semantic category")
    native_ai_resolution: Optional[bool] = Field(default=None, description="True if resolution matches standard generative diffusion aspect ratios")
    camera_hardware_exif: Optional[bool] = Field(default=None, description="True if physical camera hardware Make/Model metadata detected")
    generative_synthesis_confirmed: Optional[bool] = Field(default=None, description="True if diffusion/generative synthesis signatures confirmed")
    ai_generator_profile: Optional[str] = Field(default=None, description="Identified generative framework profile")

    class Config:
        extra = "ignore"


class ExplainabilityResult(BaseModel):
    """2-line explainability generated by Groq Agent or Forensic Rules Engine."""
    explanation: str = Field(..., description="Concise 2-line explanation of why the image belongs to the detected class")
    line_1: str = Field(..., description="Sentence 1: Primary visual/spectral forensic cue detected")
    line_2: str = Field(..., description="Sentence 2: Diagnostic conclusion validating the class membership")
    provider: str = Field(..., description="Source of explanation (Groq LLM model or Forensic Rules Engine)")


class DetectionResponse(BaseModel):
    """Comprehensive analysis response returned by the detector agent."""
    status: str = Field(default="success", description="Status of detection pipeline")
    predicted_class: str = Field(..., description="Top predicted class: real, ai_generated, faceswap, or photoshop")
    confidence: float = Field(..., description="Confidence probability of the predicted class")
    is_fake: bool = Field(..., description="True if classified as ai_generated, faceswap, or photoshop")
    class_probabilities: List[ClassConfidence] = Field(..., description="Confidence breakdown across all 4 classes")
    forensics: ForensicMetrics = Field(..., description="Extracted spatial and spectral forensic metrics")
    explainability: ExplainabilityResult = Field(..., description="2-line explainable forensic rationale")
    inference_time_ms: float = Field(..., description="Execution time in milliseconds")
    timestamp: str = Field(..., description="UTC ISO timestamp of analysis")
    session_id: Optional[str] = Field(default=None, description="Active LangGraph session ID")
    image_id: Optional[str] = Field(default=None, description="Unique image identifier")
    image_url: Optional[str] = Field(default=None, description="URL path to uploaded image")
    uploaded_images: Optional[List[Dict[str, Any]]] = Field(default=None, description="All registered user images in session")


class HealthResponse(BaseModel):
    """Health check endpoint response schema."""
    status: str
    model_loaded: bool
    model_path: str
    device: str
    groq_configured: bool
    groq_model: str
    supported_classes: List[str]
    app_version: str


class ClassDetail(BaseModel):
    name: str
    display_name: str
    category: str
    description: str


class ClassesListResponse(BaseModel):
    supported_classes: List[ClassDetail]


class ChatRequest(BaseModel):
    """Conversational follow-up query schema using LangGraph memory."""
    query: str = Field(..., description="User follow-up question regarding the image or forensics")
    session_id: Optional[str] = Field(default=None, description="Active LangGraph session ID")
    image_id: Optional[str] = Field(default=None, description="Target image ID if questioning a specific past image")
    user_id: Optional[int] = Field(default=None, description="Authenticated user ID")
    groq_api_key: Optional[str] = Field(default=None, description="Optional Groq API key override")


class ChatResponse(BaseModel):
    """Conversational answer schema with LangGraph checkpointed memory and registered images."""
    status: str = Field(default="success")
    session_id: str = Field(..., description="LangGraph session thread ID")
    image_id: Optional[str] = Field(default=None, description="Referenced image ID")
    user_id: Optional[int] = Field(default=None, description="Authenticated user ID")
    query: str = Field(..., description="Original user query")
    answer: str = Field(..., description="Forensic AI Agent response")
    uploaded_images: List[Dict[str, Any]] = Field(default_factory=list, description="All registered user uploaded images")
    timestamp: str = Field(..., description="UTC ISO timestamp of interaction")


class UploadedImageRecord(BaseModel):
    """Metadata record of an uploaded image registered in session memory."""
    image_id: str
    user_id: Optional[int] = None
    filename: str
    image_url: str
    timestamp: str
    predicted_class: Optional[str] = None
    confidence: Optional[float] = None
    is_fake: Optional[bool] = None
    class_probabilities: Optional[List[Dict[str, Any]]] = None
    forensics: Optional[Dict[str, Any]] = None
    explainability: Optional[Dict[str, Any]] = None


class UploadedImagesResponse(BaseModel):
    """Response containing all registered uploaded images for a session and user."""
    session_id: str
    user_id: Optional[int] = None
    username: Optional[str] = None
    total_images: int
    images: List[Dict[str, Any]]


class SessionHistoryResponse(BaseModel):
    """Response containing LangGraph conversational message history and images."""
    session_id: str
    user_id: Optional[int] = None
    messages: List[Dict[str, Any]]
    uploaded_images: List[Dict[str, Any]]


class RegisterRequest(BaseModel):
    """User registration schema."""
    username: str = Field(..., min_length=3, max_length=50, description="Unique username")
    password: str = Field(..., min_length=6, description="Password with minimum 6 characters")
    confirm_password: str = Field(..., min_length=6, description="Password confirmation")


class LoginRequest(BaseModel):
    """User authentication schema."""
    username: str = Field(..., description="Registered username")
    password: str = Field(..., description="Account password")


class AuthResponse(BaseModel):
    """Authentication token and profile response schema."""
    status: str = Field(default="success")
    message: str = Field(..., description="Status message")
    user_id: int = Field(..., description="Authenticated user ID")
    username: str = Field(..., description="User handle")
    token: str = Field(..., description="Session authentication token")


class UserProfileResponse(BaseModel):
    """Public user identity schema."""
    id: int
    username: str
    created_at: str


